@dataclass
class Operation:
    name: str
    family: str | None
    run: int
    label: str
    wall_s: float
    error: str | None = None
    detail: dict[str, Any] = field(default_factory=dict)
    queries: list[dict[str, Any]] = field(default_factory=list)


class Recorder:
    def __init__(self, admin: Admin, run_id: str) -> None:
        self.admin = admin
        self.run_id = run_id
        self.operations: list[Operation] = []

    async def measure(
        self,
        step: int,
        name: str,
        action: Callable[[], Awaitable[Any]],
        *,
        family: str | None = None,
        run: int = 1,
    ) -> Any:
        from app.core.clickhouse import get_clickhouse_client

        label = f"bench:{self.run_id}:{step}:{name}:{family or '-'}:{run}"
        client = await get_clickhouse_client()
        client.set_client_setting("log_comment", label)
        started = time.perf_counter()
        error = None
        result = None
        try:
            result = await action()
        except Exception as exc:  # noqa: BLE001 - a failed query is a result here, recorded
            error = f"{type(exc).__name__}: {str(exc).splitlines()[0][:300] if str(exc) else ''}"
        finally:
            client.set_client_setting("log_comment", "")
        self.operations.append(
            Operation(name=name, family=family, run=run, label=label, wall_s=time.perf_counter() - started, error=error)
        )
        return result

    def collect(self) -> None:
        self.admin.command("SYSTEM FLUSH LOGS")
        rows = self.admin.rows(
            """
            SELECT log_comment, toString(type), query_kind, query_duration_ms, memory_usage, read_rows,
                   read_bytes, written_rows, result_rows, exception_code,
                   substring(replaceRegexpAll(query, '\\s+', ' '), 1, 90)
            FROM system.query_log
            WHERE log_comment LIKE %(prefix)s AND type != 'QueryStart'
            ORDER BY event_time_microseconds
            """,
            {"prefix": f"bench:{self.run_id}:%"},
        )
        by_label: dict[str, list[dict[str, Any]]] = {}
        for comment, kind, query_kind, duration, memory, read_rows, read_bytes, written, result, code, text in rows:
            by_label.setdefault(str(comment), []).append(
                {
                    "type": kind,
                    "kind": query_kind,
                    "duration_ms": int(duration),
                    "memory_bytes": int(memory),
                    "read_rows": int(read_rows),
                    "read_bytes": int(read_bytes),
                    "written_rows": int(written),
                    "result_rows": int(result),
                    "exception_code": int(code),
                    "query": str(text),
                }
            )
        for operation in self.operations:
            if not operation.queries:
                operation.queries = by_label.get(operation.label, [])


