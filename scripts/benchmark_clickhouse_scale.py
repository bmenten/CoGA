def estimated_step_bytes(
    model: CohortModel, new_variants: int, new_families: list[Family], last: dict[str, float], *, details: bool
) -> float:
    """The disk a step adds, with room for its merges: a merge writes its new part before
    the parts it replaces go, so the largest table (the annotations, over half of the
    shared tables) briefly takes twice its size."""
    per_variant = last.get("per_variant", 820.0 if details else 500.0)
    per_entry = last.get("per_entry", 90.0)
    entry_rows = sum(
        (model.common * 0.61 + 2 * model.rare_per_genome) if family.kind == "trio" else model.common * 0.477 + model.rare_per_genome
        for family in new_families
    )
    return 1.6 * (new_variants * per_variant + entry_rows * per_entry)


def free_disk_bytes(admin: Admin) -> int:
    server_free = int(admin.scalar("SELECT free_space FROM system.disks WHERE name = 'default'"))
    return min(server_free, shutil.disk_usage(Path.home()).free)


async def run(args: argparse.Namespace) -> dict[str, Any]:
    from app.core.clickhouse import close_clickhouse_client
    from app.services.clickhouse_interval_tracks import ensure_clickhouse_interval_table
    from app.services.clickhouse_variant_storage import ensure_clickhouse_variant_tables

    host = args.host or "127.0.0.1"
    admin = Admin(host, args.port, args.user, os.environ["CLICKHOUSE_PASSWORD"], args.database)
    assert_throwaway(admin, fresh=not args.measure_only)
    model = CohortModel(variant_scale=args.variant_scale)
    steps = sorted({int(value) for value in args.genomes.split(",") if value.strip()})
    projects = [_uuid("project", index) for index in range(args.projects)]
    results: dict[str, Any] = {
        "meta": {
            "started": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "host": {"platform": platform.platform(), "machine": platform.machine(), "cpus": os.cpu_count()},
            "server": server_facts(admin),
            "model": {**asdict(model), "common": model.common, "rare_per_genome": model.rare_per_genome},
            "backend_dir": str(args.backend_dir.resolve()),
            "backend_commit": subprocess.run(
                ["git", "-C", str(args.backend_dir.resolve()), "rev-parse", "--short", "HEAD"],
                capture_output=True,
                text=True,
                check=False,
            ).stdout.strip(),
            "projects": args.projects,
            "entries": args.entries,
            "details": not args.skip_details,
        },
        "steps": [],
    }
    run_id = secrets.token_hex(3)
    recorder = Recorder(admin, run_id)
    if not args.measure_only:
        admin.command(f"CREATE DATABASE IF NOT EXISTS {args.database}")
        admin.command(f"CREATE TABLE IF NOT EXISTS {args.database}.{MARKER_TABLE} (created DateTime DEFAULT now()) ENGINE = Log")
        await ensure_clickhouse_variant_tables(ASSEMBLY)
        await ensure_clickhouse_interval_table(ASSEMBLY)
        if args.writer_check:
            results["meta"]["writer_check"] = await writer_check(admin, args.writer_check)
            print(f"writer: {results['meta']['writer_check']}", flush=True)
    else:
        await ensure_clickhouse_variant_tables(ASSEMBLY)
    families_done: list[Family] = []
    last_bytes: dict[str, float] = {}
    for genomes in steps:
        count = families_for_genomes(model, genomes, args.projects)
        families = cohort_families(model, count, args.projects)
        new_families = families[len(families_done) :]
        if args.entries == "probes":
            probes = set(probe_families(families))
            new_families = [family for family in new_families if family in probes]
        before = founder_count(families_done)
        after = founder_count(families)
        step: dict[str, Any] = {
            "genomes": sum(family.genomes for family in families),
            "families": len(families),
            "trios": sum(1 for family in families if family.kind == "trio"),
            "singletons": sum(1 for family in families if family.kind == "singleton"),
            "founders": after,
        }
        if not args.measure_only:
            new_common = int(
                admin.scalar(
                    f"SELECT countIf({first_carrier('number')} >= {before} AND {first_carrier('number')} < {after}) "
                    f"FROM numbers_mt({model.common})"
                )
            )
            new_variants = new_common + model.rare_seen(after) - model.rare_seen(before)
            needed = estimated_step_bytes(
                model, new_variants, new_families, last_bytes, details=not args.skip_details
            )
            free = free_disk_bytes(admin)
            if free - needed < args.min_free_gb * 1024**3:
                step["skipped"] = (
                    f"needs about {_size(needed)} with {_size(free)} free (minimum {args.min_free_gb} GB free)"
                )
                results["steps"].append(step)
                print(f"step {genomes}: skipped, {step['skipped']}", flush=True)
                break
            started = time.perf_counter()
            step["shared_insert_s"] = {
                key: round(value, 1) for key, value in generate_shared(admin, model, before, after, details=not args.skip_details).items()
            }
            family_seconds = [await generate_family(admin, model, family) for family in new_families]
            if family_seconds:
                step["family_insert_s"] = {
                    "total": round(sum(family_seconds), 1),
                    "median": round(statistics.median(family_seconds), 2),
                }
            step["generation_s"] = round(time.perf_counter() - started, 1)
            print(f"step {genomes}: generated in {step['generation_s']} s", flush=True)
        families_done = families
        step["merge_wait_s"] = round(wait_for_merges(admin, args.merge_timeout), 1)
        step["distinct_variants"] = int(admin.scalar(f"SELECT count() FROM {admin.table('variants/annotation_index')}"))
        step["entries_rows"] = int(admin.scalar(f"SELECT count() FROM {admin.table('entries')}"))
        step["storage"] = storage(admin)
        sizes = {table["table"]: table["bytes_on_disk"] for table in step["storage"]}
        shared = sum(
            sizes.get(name, 0)
            for name in ("variants/details", "variants/annotations", "variants/annotation_index", "variants/gene_index")
        )
        last_bytes = {
            "per_variant": shared / max(step["distinct_variants"], 1),
            "per_entry": sizes.get("entries", 0) / max(step["entries_rows"], 1),
        }
        recorder.operations = []
        await measure_step(recorder, admin, genomes, families, projects, args.repeat)
        recorder.collect()
        step["operations"] = [asdict(operation) for operation in recorder.operations]
        if args.compare_backend_dir:
            step["compare"] = measure_with_other_backend(args, host, genomes)
        results["steps"].append(step)
        args.results.write_text(json.dumps(results, indent=1, default=str))
        print(f"step {genomes}: measured", flush=True)
        if args.measure_only:
            break
    await close_clickhouse_client()
    return results


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    started_container = False
    if args.host:
        password = args.password
    elif args.reuse_container:
        password = container_password(args.container)
    else:
        remove_container(args.container)
        password = secrets.token_hex(16)
        start_container(args.container, args.port, password, args.database, args.container_memory)
        started_container = True
    configure_app(args, args.host or "127.0.0.1", password)
    try:
        results = asyncio.run(run(args))
        args.results.write_text(json.dumps(results, indent=1, default=str))
        args.results.with_suffix(".md").write_text(markdown(results))
        print(f"results: {args.results}", flush=True)
    finally:
        if (started_container or args.reuse_container) and not args.keep_container:
            remove_container(args.container)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
