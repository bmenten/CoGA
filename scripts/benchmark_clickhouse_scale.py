def shared_sources(model: CohortModel, founders_before: int, founders_after: int) -> list[str]:
    """Index sources of the variants first carried by founders ``[before, after)``, in
    chunks of at most two million indices."""
    chunk = 2_000_000
    sources = []
    for start in range(0, model.common, chunk):
        size = min(chunk, model.common - start)
        sources.append(
            f"SELECT {start} + number AS i FROM numbers_mt({size}) "
            f"WHERE {first_carrier(f'({start} + number)')} >= {founders_before} "
            f"AND {first_carrier(f'({start} + number)')} < {founders_after}"
        )
    first = model.common + model.rare_seen(founders_before)
    last = model.common + model.rare_seen(founders_after)
    for start in range(first, last, chunk):
        sources.append(f"SELECT {start} + number AS i FROM numbers_mt({min(chunk, last - start)})")
    return sources


