def _founder_rows(model: CohortModel, founder: int, slot: int, slots: int) -> list[str]:
    """A founder's rare variants as ``(i, d0, d1, …)`` rows with its dosage in ``slot``."""
    def row(index: str, dosage: str) -> str:
        values = [dosage if position == slot else "toUInt8(0)" for position in range(slots)]
        return f"{index} AS i, " + ", ".join(f"{value} AS d{position}" for position, value in enumerate(values))

    start = model.common + model.rare_seen(founder)
    rows = [
        f"SELECT {row(f'{start} + number', 'toUInt8(1 + (' + u(f'({start} + number)', founder, 52) + ' < 0.005))')} "
        f"FROM numbers_mt({model.rare_new(founder)})"
    ]
    seen = model.rare_seen(founder)
    if seen and model.rare_recurring(founder) > 0:
        rows.append(
            f"SELECT {row(f'{model.common} + cityHash64({founder}, number, 53) % {seen}', 'toUInt8(1)')} "
            f"FROM numbers_mt({model.rare_recurring(founder)})"
        )
    return rows


def entries_insert(table: str, model: CohortModel, family: Family) -> str:
    """The family's ``entries`` rows: one per variant any member carries, with every
    member's call (hom-ref included), as a joint-called family VCF gives them."""
    founders = [sample for sample in family.samples if sample.founder is not None]
    slots = len(founders)
    common_columns = ", ".join(
        f"{common_dosage('number', sample.founder)} AS d{slot}"  # type: ignore[arg-type]
        for slot, sample in enumerate(founders)
    )
    any_carried = " + ".join(f"d{slot}" for slot in range(slots))
    parts = [f"SELECT number AS i, {common_columns} FROM numbers_mt({model.common}) WHERE {any_carried} > 0"]
    for slot, sample in enumerate(founders):
        parts.extend(_founder_rows(model, sample.founder, slot, slots))  # type: ignore[arg-type]
    grouped = (
        "SELECT i, " + ", ".join(f"max(d{slot}) AS d{slot}" for slot in range(slots))
        + " FROM (" + " UNION ALL ".join(parts) + ") GROUP BY i"
    )
    if family.kind == "trio":
        # The child takes one allele of each parent: a homozygous parent's always, a
        # heterozygous parent's with probability one half.
        child = family.index * 10
        inherit = (
            f"(if(d0 = 2, 1, if(d0 = 1, {u('i', child, 50)} < 0.5, 0)) + "
            f"if(d1 = 2, 1, if(d1 = 1, {u('i', child, 51)} < 0.5, 0)))"
        )
        dosages = f"SELECT i, [toUInt8({inherit}), d0, d1] AS dos FROM ({grouped})"
    else:
        dosages = f"SELECT i, [d0] AS dos FROM ({grouped})"
    members = len(family.samples)
    sample_ids = _array([sample.sample_id for sample in family.samples])
    calls = (
        f"SELECT *, "
        f"arrayMap(k -> toUInt32(18 + cityHash64(i, k, {family.index}, 41) % 30), range({members})) AS dp, "
        f"arrayMap(k -> 0.3 + 0.4 * {u('i', 'k', family.index, 42)}, range({members})) AS frac "
        f"FROM ({variant_columns(model, dosages, extra=('dos',))})"
    )
    ad = (
        "arrayMap((d, n, f) -> if(d = 0, [n, toUInt32(0)], if(d = 2, [toUInt32(0), n], "
        "[n - toUInt32(round(n * f)), toUInt32(round(n * f))])), dos, dp, frac)"
    )
    return (
        f"INSERT INTO {table} (key, variantId, annotation_version, annotationSetHash, project_guid, "
        "family_guid, xpos, chrom, pos, ref, alt, source, rsid, is_gnomad_gt_5_percent, "
        "is_annotated_in_any_gene, gene_symbols, filters, qual, `calls.sampleId`, `calls.gt`, `calls.gq`, "
        "`calls.dp`, `calls.ab`, `calls.af`, `calls.ad`, `calls.ps`, `calls.filters`, `calls.metrics`, sign) "
        f"SELECT key, variant_id, 'current', aset_hash, '{family.project_uuid}', '{family.family_uuid}', "
        f"xpos, chrom, pos, ref, alt, '{SOURCE}', rsid, gt5, genic, "
        "if(genic, [gene], CAST([] AS Array(String))), CAST([] AS Array(String)), "
        f"toFloat32(round(30 + 40 * {u('i', family.index, 43)}, 2)), {sample_ids}, "
        "arrayMap(d -> ['0/0', '0/1', '1/1'][d + 1], dos), "
        f"arrayMap(k -> toUInt16(20 + cityHash64(i, k, {family.index}, 44) % 80), range({members})), "
        "dp, arrayMap(a -> a[2] / (a[1] + a[2]), ad_values), "
        "arrayMap(a -> [a[2] / (a[1] + a[2])], ad_values), ad_values, "
        f"arrayMap(k -> CAST(NULL AS Nullable(UInt64)), range({members})), "
        f"arrayMap(k -> CAST([] AS Array(String)), range({members})), "
        f"arrayMap(k -> CAST(map(), 'Map(String, Float32)'), range({members})), 1 "
        f"FROM (SELECT *, {ad} AS ad_values FROM ({calls}))"
    )


