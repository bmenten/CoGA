#!/usr/bin/env python3
"""Scale benchmark of CoGA's ClickHouse small-variant storage on a synthetic cohort.

It answers one question: how do the family search, the Variant Explorer, a family's
delete or overwrite and the integrity check behave as the cohort grows towards 1,000
whole genomes? Results are written as JSON and summarised as Markdown; the write-up is
``docs/clickhouse-scale-benchmark.md``.

What it does, step by step:

1. Starts a throwaway ClickHouse container (the image of ``docker-compose.yml``, with the
   repository's ``clickhouse/users.d/memory-guards.xml``, so every query is capped at
   4 GB as in production) and removes it at the end. With ``--host``/``--port`` it uses a
   server you started yourself, and refuses one that holds any database but its own: it
   never writes next to data it did not create.
2. Creates the tables with the app's own DDL (``ensure_clickhouse_variant_tables``).
3. For each scale step (``--genomes 50,250,500,1000``) adds families until the cohort has
   that many genomes: three trios for every singleton, 300 trios and 100 singletons at
   1,000. Every value is synthetic (``PROBAND-0001``, ``MOTHER-0001``, ``FATHER1-0001``,
   ``FAM-0001``) and generated by ClickHouse itself (``INSERT … SELECT``), with the columns
   the storage writer derives (``clickhouse_variant_rows._small_variant_entry_rows``):
   one ``entries`` row per family and variant with the members' calls, and per distinct
   variant one ``variants/details`` row with its annotation JSON, one
   ``variants/annotation_index`` row, about six ``variants/annotations`` rows (one per
   transcript) and two ``variants/gene_index`` rows when it lies in a gene. The writer
   itself is measured once (``--writer-check``) for comparison: at its rate a cohort of
   1,000 genomes would take days to write.
4. Measures, after the step's merges have settled, the app's own ClickHouse calls, each
   tagged with a ``log_comment`` and read back from ``system.query_log`` (duration,
   memory, rows and bytes read):
   - the family search's list and count queries (``_fetch_small_variant_rows``,
     ``_count_small_variant_rows_bounded``) for a trio and a singleton: rare and
     HIGH/MODERATE impact, rare only (gnomAD AF at most 1 %), a 5,300-gene panel with
     its gene loci (Mendeliome-like), one gene;
   - the Variant Explorer search (``search_global_small_variants``, its Postgres parts
     stubbed: every project in scope, no review filter), unfiltered and filtered;
   - one trio's overwrite as the import runs it (``snapshot_family_clickhouse_state``,
     ``delete_family_small_variants``, ``restore_family_clickhouse_state``,
     ``discard_family_clickhouse_snapshot``), with the parts its mutations rewrote
     (``system.part_log``);
   - the 6-hourly integrity check (``check_clickhouse_variant_integrity``);
   - each table's rows, parts and bytes on disk.

The cohort model (``CohortModel``) gives each genome about 4.8 M small variants: common
ones (gnomAD AF over 1 %) drawn by hash from a pool of 9.1 M, and rare ones, of which each
founder adds new ones along ``T(n) = 450,000 · n^0.725`` (fitted to about 60 M distinct
variants for 700 unrelated genomes, the founders of 1,000 genomes in trios). A trio's
child carries one parental allele of each parent at random. ``--variant-scale`` shrinks
every pool by the same factor, to fit a small disk; the per-family numbers then shrink by
it too, and the write-up says how to read them.

Run it on a server with room: 1,000 genomes take about 240 GB of disk (300 GB with merges)
and most of a day to generate; ``--variant-scale 0.25`` takes about a quarter of both::

    python scripts/benchmark_clickhouse_scale.py --genomes 50,250,500,1000 \
        --results /tmp/coga-scale.json

To compare two versions of the query code on the same data, measure every step a second
time with the other checkout's backend, or keep the container and measure it later::

    python scripts/benchmark_clickhouse_scale.py --genomes 50,250 --results a.json \
        --compare-backend-dir ../other-checkout/backend
    python scripts/benchmark_clickhouse_scale.py --genomes 50 --keep-container --results a.json
    python scripts/benchmark_clickhouse_scale.py --genomes 50 --reuse-container --measure-only \
        --backend-dir ../other-checkout/backend --results b.json
"""

