def _summary(operations: list[dict[str, Any]]) -> dict[str, Any]:
    walls = [operation["wall_s"] for operation in operations]
    queries = [query for operation in operations for query in operation["queries"]]
    errors = sorted({operation["error"] for operation in operations if operation["error"]})
    return {
        "median_wall_s": round(statistics.median(walls), 3) if walls else None,
        "max_memory_bytes": max((query["memory_bytes"] for query in queries), default=0),
        "read_rows_per_run": round(sum(query["read_rows"] for query in queries) / max(len(operations), 1)),
        "read_bytes_per_run": round(sum(query["read_bytes"] for query in queries) / max(len(operations), 1)),
        "errors": errors,
        "exception_codes": sorted({query["exception_code"] for query in queries if query["exception_code"]}),
    }


def _size(value: float) -> str:
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if abs(value) < 1024 or unit == "TiB":
            return f"{value:.0f} {unit}" if unit == "B" else f"{value:.2f} {unit}"
        value /= 1024
    return f"{value:.2f} TiB"


def markdown(results: dict[str, Any]) -> str:
    lines = ["# ClickHouse scale benchmark results", ""]
    meta = results["meta"]
    lines.append(
        f"ClickHouse {meta['server']['clickhouse_version']}, {meta['server']['server_cpus']} CPUs and "
        f"{_size(meta['server']['os_memory_total'])} seen by the server, per-query cap "
        f"{_size(meta['server']['per_query_memory_cap'] or 0)}; variant scale {meta['model']['variant_scale']}."
    )
    lines.append("")
    for step in results["steps"]:
        if "skipped" in step:
            lines += [f"## {step['genomes']} genomes: not run, {step['skipped']}", ""]
            continue
        lines.append(
            f"## {step['genomes']} genomes ({step['trios']} trios, {step['singletons']} singletons): "
            f"{step['distinct_variants']:,} distinct variants, {step['entries_rows']:,} entries rows"
        )
        lines.append("")
        compared: dict[tuple[str, str], list[dict[str, Any]]] = {}
        for operation in step.get("compare", {}).get("operations", []):
            compared.setdefault((operation["name"], operation["family"] or ""), []).append(operation)
        header = "| Operation | Family | Median s | Max memory | Rows read / run | Errors |"
        if compared:
            header += f" {step['compare']['backend_commit']}: median s | max memory |"
        lines.append(header)
        lines.append("| --- | --- | ---: | ---: | ---: | --- |" + (" ---: | ---: |" if compared else ""))
        groups: dict[tuple[str, str], list[dict[str, Any]]] = {}
        for operation in step["operations"]:
            groups.setdefault((operation["name"], operation["family"] or ""), []).append(operation)
        for (name, family), operations in groups.items():
            summary = _summary(operations)
            line = (
                f"| {name} | {family} | {summary['median_wall_s']} | {_size(summary['max_memory_bytes'])} | "
                f"{summary['read_rows_per_run']:,} | {'; '.join(summary['errors'])[:120]} |"
            )
            if (name, family) in compared:
                other = _summary(compared[(name, family)])
                line += f" {other['median_wall_s']} | {_size(other['max_memory_bytes'])} |"
            lines.append(line)
        lines.append("")
        lines.append("| Table | Rows | Parts | On disk | Bytes/row |")
        lines.append("| --- | ---: | ---: | ---: | ---: |")
        for table in step["storage"]:
            lines.append(
                f"| {table['table']} | {table['rows']:,} | {table['parts']} | {_size(table['bytes_on_disk'])} | "
                f"{table['bytes_per_row']} |"
            )
        lines.append("")
    return "\n".join(lines)


