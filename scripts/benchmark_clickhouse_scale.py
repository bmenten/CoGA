def compose_clickhouse_image() -> str:
    text = (REPO_ROOT / "docker-compose.yml").read_text()
    match = re.search(r"image:\s*(clickhouse/clickhouse-server:\S+)", text)
    if not match:
        raise SystemExit("No ClickHouse image in docker-compose.yml")
    return match.group(1)


def start_container(name: str, port: int, password: str, database: str, memory: str | None) -> None:
    command = [
        "docker", "run", "-d", "--name", name,
        "-e", f"CLICKHOUSE_DB={database}", "-e", "CLICKHOUSE_USER=bench",
        "-e", f"CLICKHOUSE_PASSWORD={password}", "-e", "CLICKHOUSE_DEFAULT_ACCESS_MANAGEMENT=1",
        "-p", f"127.0.0.1:{port}:8123", "--ulimit", "nofile=262144:262144",
        "-v", f"{MEMORY_GUARDS}:/etc/clickhouse-server/users.d/memory-guards.xml:ro",
    ]
    if memory:
        command += ["--memory", memory]
    subprocess.run([*command, compose_clickhouse_image()], check=True, stdout=subprocess.DEVNULL)
    for _attempt in range(60):
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/ping", timeout=2) as response:
                if response.read().strip() == b"Ok.":
                    return
        except OSError:
            pass
        time.sleep(1)
    raise SystemExit("The benchmark's ClickHouse container did not start")


def remove_container(name: str) -> None:
    subprocess.run(["docker", "rm", "-f", "-v", name], check=False, stdout=subprocess.DEVNULL)


def container_password(name: str) -> str:
    result = subprocess.run(
        ["docker", "inspect", "-f", "{{range .Config.Env}}{{println .}}{{end}}", name],
        check=True,
        capture_output=True,
        text=True,
    )
    for line in result.stdout.splitlines():
        if line.startswith("CLICKHOUSE_PASSWORD="):
            return line.split("=", 1)[1]
    raise SystemExit(f"Container {name} has no CLICKHOUSE_PASSWORD")


class Admin:
    """A plain client for the generator and the system tables, apart from the app's."""

    def __init__(self, host: str, port: int, user: str, password: str, database: str) -> None:
        import clickhouse_connect

        self.database = database
        self.client = clickhouse_connect.get_client(
            host=host,
            port=port,
            username=user,
            password=password,
            database="default",
            send_receive_timeout=3600,
            settings={"max_execution_time": 0, "max_memory_usage": 0, "max_insert_threads": 4},
        )

    def rows(self, query: str, parameters: dict[str, Any] | None = None) -> list[tuple[Any, ...]]:
        return list(self.client.query(query, parameters=parameters or {}).result_rows)

    def scalar(self, query: str, parameters: dict[str, Any] | None = None) -> Any:
        rows = self.rows(query, parameters)
        return rows[0][0] if rows else None

    def command(self, query: str, settings: dict[str, Any] | None = None) -> None:
        self.client.command(query, settings=settings or {})

    def table(self, suffix: str) -> str:
        return f"{self.database}.`{ASSEMBLY}/SNV_INDEL/{suffix}`"


def assert_throwaway(admin: Admin, *, fresh: bool) -> None:
    databases = {str(row[0]) for row in admin.rows("SELECT name FROM system.databases")}
    others = databases - SERVER_DATABASES - {admin.database}
    if others:
        raise SystemExit(
            f"Refusing to run: the server holds other databases ({', '.join(sorted(others))}). "
            "The benchmark only runs against a throwaway server it can fill and drop."
        )
    if admin.database not in databases:
        return
    tables = {
        str(row[0])
        for row in admin.rows("SELECT name FROM system.tables WHERE database = %(db)s", {"db": admin.database})
    }
    if fresh and tables - {MARKER_TABLE}:
        raise SystemExit(f"Refusing to generate: database {admin.database} is not empty (use --measure-only)")
    if not fresh and MARKER_TABLE not in tables:
        raise SystemExit(f"Database {admin.database} holds no benchmark data")


