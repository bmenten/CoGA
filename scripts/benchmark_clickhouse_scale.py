def panel_constraints(admin: Admin) -> tuple[Any, int]:
    """The Mendeliome-like panel: about 5,300 protein-coding genes with their loci, as the
    family page reads a panel (``_fetch_panel_constraints``: genes and regions)."""
    from app.services.clickhouse_variant_records import PanelFilterConstraints, Region

    starts = []
    total = 0
    for length in CHROMOSOME_LENGTHS:
        starts.append(total)
        total += length
    rows = admin.rows(
        f"""
        SELECT concat('SG', toString(gb)) AS gene, ci, start, least(start + gl - 1, chrom_length) AS stop
        FROM (
            SELECT number AS gb,
                   toUInt32({u('gb', 11)} * 0.05 * {GENE_BIN}) AS gs,
                   toUInt32((0.30 + 0.65 * {u('gb', 12)}) * {GENE_BIN}) AS gl,
                   gb * {GENE_BIN} + gs AS gstart,
                   arrayFirstIndex(e -> e > gstart, {_array([s + l for s, l in zip(starts, CHROMOSOME_LENGTHS)])}) AS ci,
                   toUInt32(gstart - {_array(starts)}[ci] + 1) AS start,
                   {_array(CHROMOSOME_LENGTHS)}[ci] AS chrom_length
            FROM numbers({GENE_BINS})
            WHERE gb % 2 = 0 AND {u('gb', 60)} < {PANEL_SHARE}
        )
        ORDER BY gb
        """
    )
    genes = tuple(str(row[0]) for row in rows)
    regions = tuple(Region(chr=CHROMOSOMES[int(row[1]) - 1], start=int(row[2]), end=int(row[3])) for row in rows)
    return PanelFilterConstraints(genes=genes, regions=regions), len(genes)


