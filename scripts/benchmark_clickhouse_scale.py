async def measure_step(
    recorder: Recorder,
    admin: Admin,
    step: int,
    families: list[Family],
    projects: list[str],
    repeat: int,
) -> None:
    from app.services import variant_explorer_service as explorer
    from app.services.clickhouse_family_snapshot import (
        discard_family_clickhouse_snapshot,
        restore_family_clickhouse_state,
        snapshot_family_clickhouse_state,
    )
    from app.services.clickhouse_family_variants import (
        _count_small_variant_rows_bounded,
        _fetch_small_variant_rows,
    )
    from app.services.clickhouse_variant_storage import (
        check_clickhouse_variant_integrity,
        delete_family_small_variants,
    )
    from app.services.family_variant_filters import SmallVariantQueryFilters

    trio, singleton, overwritten = probe_families(families)
    panel, _genes = panel_constraints(admin)
    searches: dict[str, tuple[Any, Any]] = {
        "family.rare_impact": (
            SmallVariantQueryFilters(page=1, page_size=50, max_gnomad_af=0.01, impact=["HIGH", "MODERATE"]),
            None,
        ),
        "family.rare": (SmallVariantQueryFilters(page=1, page_size=50, max_gnomad_af=0.01), None),
        "family.panel": (SmallVariantQueryFilters(page=1, page_size=50), panel),
        "family.panel_rare_impact": (
            SmallVariantQueryFilters(page=1, page_size=50, max_gnomad_af=0.01, impact=["HIGH", "MODERATE"]),
            panel,
        ),
        "family.gene": (SmallVariantQueryFilters(page=1, page_size=50, gene=f"SG{SINGLE_GENE_BIN}"), None),
    }
    for family in (trio, singleton):
        context = family_context(family)
        for name, (filters, constraints) in searches.items():
            for run in range(1, repeat + 1):

                async def search(context: Any = context, filters: Any = filters, constraints: Any = constraints) -> Any:
                    rows = await _fetch_small_variant_rows(
                        context, filters, limit=51, offset=0, panel_constraints=constraints
                    )
                    total = await _count_small_variant_rows_bounded(
                        context, filters, panel_constraints=constraints
                    )
                    return len(rows), total

                result = await recorder.measure(step, name, search, family=family.kind, run=run)
                if result is not None:
                    recorder.operations[-1].detail = {"page_rows": result[0], "total": list(result[1])}

    stub_explorer_postgres(projects)
    explorer_filters = {
        "explorer.unfiltered": explorer.GlobalVariantFilters(),
        "explorer.rare_impact": explorer.GlobalVariantFilters(max_gnomad_af=0.01, impacts=["HIGH", "MODERATE"]),
        "explorer.gene": explorer.GlobalVariantFilters(gene=f"SG{SINGLE_GENE_BIN}"),
    }
    for name, global_filters in explorer_filters.items():
        for run in range(1, repeat + 1):

            async def explore(global_filters: Any = global_filters) -> Any:
                page = await explorer.search_global_small_variants(
                    None,  # type: ignore[arg-type]
                    user=None,  # type: ignore[arg-type]
                    filters=global_filters,
                    assembly_id="bench-assembly",
                )
                return page.total, len(page.variants)

            result = await recorder.measure(step, name, explore, run=run)
            if result is not None:
                recorder.operations[-1].detail = {"total": result[0], "page_rows": result[1]}

    # One trio overwritten as the import does it; its rows are put back by the restore.
    since = admin.scalar("SELECT now64(6)")
    snapshot = await recorder.measure(
        step,
        "overwrite.snapshot",
        lambda: snapshot_family_clickhouse_state(ASSEMBLY, overwritten.family_uuid, owner=f"bench-{step}"),
        family=overwritten.kind,
    )
    # As the import: no delete without a snapshot to put the rows back from, or the next
    # step would measure a cohort without this family.
    if snapshot is not None:
        await recorder.measure(
            step,
            "overwrite.delete",
            lambda: delete_family_small_variants(ASSEMBLY, overwritten.family_uuid),
            family=overwritten.kind,
        )
        await recorder.measure(
            step, "overwrite.restore", lambda: restore_family_clickhouse_state(snapshot), family=overwritten.kind
        )
        await recorder.measure(
            step, "overwrite.discard", lambda: discard_family_clickhouse_snapshot(snapshot), family=overwritten.kind
        )
    admin.command("SYSTEM FLUSH LOGS")
    mutated = admin.rows(
        """
        SELECT table, count(), sum(rows), sum(size_in_bytes), sum(read_rows), sum(read_bytes),
               round(sum(duration_ms) / 1000, 2)
        FROM system.part_log
        WHERE event_type = 'MutatePart' AND database = %(db)s AND event_time_microseconds >= %(since)s
        GROUP BY table ORDER BY table
        """,
        {"db": admin.database, "since": since},
    )
    for operation in recorder.operations:
        if operation.name == "overwrite.delete" and operation.label.split(":")[2] == str(step):
            operation.detail = {
                "mutated_parts": [
                    {
                        "table": str(table),
                        "parts": int(parts),
                        "rows": int(rows),
                        "bytes": int(size),
                        "read_rows": int(read_rows),
                        "read_bytes": int(read_bytes),
                        "seconds": float(seconds),
                    }
                    for table, parts, rows, size, read_rows, read_bytes, seconds in mutated
                ]
            }
    report = await recorder.measure(step, "integrity.check", lambda: check_clickhouse_variant_integrity(ASSEMBLY))
    if report is not None:
        recorder.operations[-1].detail = {
            "status": report["status"],
            "gene_index_consistent": report["gene_index_consistency"]["consistent"],
        }


def storage(admin: Admin) -> list[dict[str, Any]]:
    rows = admin.rows(
        """
        SELECT table, count(), sum(rows), sum(bytes_on_disk), sum(data_uncompressed_bytes), max(bytes_on_disk)
        FROM system.parts
        WHERE database = %(db)s AND active AND table LIKE %(prefix)s
        GROUP BY table ORDER BY sum(bytes_on_disk) DESC
        """,
        {"db": admin.database, "prefix": f"{ASSEMBLY}/SNV_INDEL/%"},
    )
    columns = admin.rows(
        """
        SELECT table, name, data_compressed_bytes
        FROM system.columns
        WHERE database = %(db)s AND table LIKE %(prefix)s
        ORDER BY data_compressed_bytes DESC
        """,
        {"db": admin.database, "prefix": f"{ASSEMBLY}/SNV_INDEL/%"},
    )
    largest: dict[str, list[tuple[str, int]]] = {}
    for table, name, size in columns:
        if len(largest.setdefault(str(table), [])) < 4:
            largest[str(table)].append((str(name), int(size)))
    return [
        {
            "table": str(table).split("/SNV_INDEL/", 1)[1],
            "parts": int(parts),
            "rows": int(total_rows),
            "bytes_on_disk": int(on_disk),
            "uncompressed_bytes": int(uncompressed),
            "largest_part_bytes": int(largest_part),
            "bytes_per_row": round(int(on_disk) / int(total_rows), 1) if total_rows else None,
            "largest_columns": largest.get(str(table), []),
        }
        for table, parts, total_rows, on_disk, uncompressed, largest_part in rows
    ]


def server_facts(admin: Admin) -> dict[str, Any]:
    row = admin.rows(
        """
        SELECT version(),
               (SELECT toUInt64(value) FROM system.server_settings WHERE name = 'max_server_memory_usage'),
               (SELECT toUInt64(value) FROM system.asynchronous_metrics WHERE metric = 'OSMemoryTotal'),
               toUInt32(extract(toString(getSetting('max_threads')), '\\d+')),
               (SELECT free_space FROM system.disks WHERE name = 'default')
        """
    )[0]
    cap = admin.scalar(
        "SELECT value FROM system.settings_profile_elements WHERE setting_name = 'max_memory_usage' LIMIT 1"
    )
    return {
        "clickhouse_version": str(row[0]),
        "max_server_memory_usage": int(row[1]),
        "os_memory_total": int(row[2]),
        "server_cpus": int(row[3]),
        "server_free_disk_bytes": int(row[4]),
        "per_query_memory_cap": int(cap) if cap is not None else None,
    }


