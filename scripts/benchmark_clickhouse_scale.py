def wait_for_merges(admin: Admin, timeout: float) -> float:
    started = time.monotonic()
    quiet_since: float | None = None
    while time.monotonic() - started < timeout:
        busy = admin.scalar(
            "SELECT (SELECT count() FROM system.merges WHERE database = %(db)s) + "
            "(SELECT count() FROM system.mutations WHERE database = %(db)s AND NOT is_done)",
            {"db": admin.database},
        )
        if busy:
            quiet_since = None
        elif quiet_since is None:
            quiet_since = time.monotonic()
        elif time.monotonic() - quiet_since >= 10:
            break
        time.sleep(2)
    return time.monotonic() - started


def generate_shared(
    admin: Admin, model: CohortModel, before: int, after: int, *, details: bool
) -> dict[str, float]:
    timings: dict[str, float] = {}
    builders = {
        "variants/details": details_insert,
        "variants/annotations": annotations_insert,
        "variants/annotation_index": annotation_index_insert,
        "variants/gene_index": gene_index_insert,
    }
    if not details:
        del builders["variants/details"]
    # A variant's annotation JSON is about 3.8 KB: in blocks of the default 65,536 rows on
    # every thread, the details insert held 2.8 GiB and failed on a server of 3.4 GB.
    small_blocks = {"max_block_size": 8192, "max_threads": 4, "max_insert_threads": 2}
    for suffix, builder in builders.items():
        started = time.perf_counter()
        for source in shared_sources(model, before, after):
            admin.command(
                builder(admin.table(suffix), model, source),
                settings=small_blocks if suffix == "variants/details" else None,
            )
        timings[suffix] = time.perf_counter() - started
    return timings


